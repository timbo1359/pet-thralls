	/**
	 * Finds a pet's default look by its collection log / item name, ignoring case.
	 *
	 * @return the pet, or {@code null} if the name isn't a pet
	 */
	static ThrallPet fromItemName(String name)
	{
		for (ThrallPet pet : values())
		{
			if (pet != NONE && pet.defaultLook && pet.petName.equalsIgnoreCase(name))
			{
				return pet;
			}
		}
		return null;
	}

	/**
	 * The dropdown text: alternate looks indented under their pet, coloured green
	 * when the pet is unlocked and red when it isn't.
	 */
	@Override
	public String toString()
	{
		String text = defaultLook ? label : INDENT + label;
		Set<Integer> unlocked = unlockedItems;
		if (this == NONE || unlocked == null)
		{
			return text;
		}
		return "<html><font color='" + (unlocked.contains(itemId) ? UNLOCKED_COLOR : LOCKED_COLOR) + "'>"
			+ text + "</font></html>";
	}
